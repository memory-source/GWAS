"""Aggregate the GPU/scale round outputs into one results table + a summary.

Reads every results/raw/s2x_*.json and s3x_*.json produced by the GPU round and
emits:
  - results/raw/gpu_round_summary.json   (machine-readable, keys normalized)
  - refine-logs/GPU_ROUND_RESULTS.md     (human-readable tables)

No new computation; purely a merge so the paper/review can cite one artifact.
"""
import glob
import json
import os
import sys

import numpy as np

ROOT = "/data/lvvyongji1/GWAS"
RAW = os.path.join(ROOT, "results", "raw")
OUT_MD = os.path.join(ROOT, "refine-logs", "GPU_ROUND_RESULTS.md")


def load(name):
    p = os.path.join(RAW, name)
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def merge_s27():
    cells = {}
    for f in sorted(glob.glob(os.path.join(RAW, "s27_gpu_scale_shard*.json"))):
        d = json.load(open(f))
        for k, v in d["grid"].items():
            cells.setdefault(k, v)      # first shard wins (identical cells)
    return dict(cells=cells)


def merge_paired(shards):
    """Pool the s29 paired shards HONESTLY: each shard holds 200 per-seed deltas
    per cell, never one shard's aggregate. Concatenate the per-seed deltas and
    recompute mean/CI/P(>0) over all seeds."""
    pooled = {}
    for f in shards:
        d = json.load(open(f))
        for k, v in d.get("paired", {}).items():
            pooled.setdefault(k, []).extend(v.get("per_seed_delta", []))
    out = {}
    for k, deltas in pooled.items():
        d = np.array(deltas, dtype=float)
        if d.size == 0:
            continue
        rng = np.random.default_rng(7)
        boot = d[rng.integers(0, d.size, size=(10000, d.size))].mean(1)
        out[k] = dict(n_seeds=int(d.size), delta_mean=float(d.mean()),
                      delta_std=float(d.std()),
                      delta_ci_lo=float(np.percentile(boot, 2.5)),
                      delta_ci_hi=float(np.percentile(boot, 97.5)),
                      p_delta_gt0=float((d > 0).mean()))
    return out


def main():
    import numpy as np
    summary = {}
    md = ["# GPU / scale round — consolidated results",
          "", "Generated by `code/gpu_round_summary.py` from `results/raw/s2x_*.json`.",
          ""]

    # ---- s27 boundary grid
    s27 = merge_s27()
    summary["s27_boundary"] = s27
    # eigenvalue-only control across all biobank cells
    eig_vals = [v["pc_eigonly"] for v in s27["cells"].values() if "pc_eigonly" in v]
    md += ["## S27 — biobank-scale boundary grid", ""]
    if eig_vals:
        md += ["_Eigenvalue-only control across all %d cells: %.3f–%.3f (chance)._" % (
            len(eig_vals), min(eig_vals), max(eig_vals)), ""]
    md += ["| cell (study/group, M, Fst) | AF | PC | PC-AF | PC(ref-basis) | PC(eig-only) | in-sample gap | fst_like |",
           "|---|---|---|---|---|---|---|---|"]
    for k in sorted(s27["cells"]):
        v = s27["cells"][k]
        md.append("| %s | %.3f | %.3f | %+.3f | %.3f | %s | %.3f | %.3f |" % (
            k, v["af_only"], v["pc_calibrated"], v["delta_pc_minus_af"],
            v.get("pc_refbasis", float("nan")),
            ("%.3f" % v["pc_eigonly"]) if "pc_eigonly" in v else "—",
            v.get("pc_in_sample_gap", float("nan")),
            v.get("fst_like", float("nan"))))
    md.append("")

    # ---- s28 permutation nulls
    s28 = {}
    nperm_seen = None
    for f in sorted(glob.glob(os.path.join(RAW, "s28_permnull_shard*.json"))):
        d = json.load(open(f))
        s28.update(d.get("grid", {}))
        if d.get("cfg", {}).get("nperm"):
            nperm_seen = d["cfg"]["nperm"]
    summary["s28_permnull"] = s28
    md += [f"## S28 — stratified permutation nulls ({nperm_seen or '?'} permutations/cell)", "",
           "| cell | AF (p) | PC (p) | PC-AF [95% CI] |", "|---|---|---|---|"]
    for k in sorted(s28):
        v = s28[k]
        md.append("| %s | %.3f (p=%.0e) | %.3f (p=%.0e) | %+.3f [%+.3f,%+.3f] |" % (
            k, v["af_auc"], v["af_p_max"], v["pc_auc"], v["pc_p_max"],
            v["delta"], v["delta_ci"]["lo"], v["delta_ci"]["hi"]))
    md.append("")

    # ---- s29 paired negation (pooled) + ladder
    s29 = {}
    paired_files = sorted(glob.glob(os.path.join(RAW, "s29_negation_shard*.json")))
    slow = os.path.join(RAW, "s29_negation_slow.json")
    if os.path.exists(slow):
        paired_files.append(slow)
    s29_paired = merge_paired(paired_files)
    lad = os.path.join(RAW, "s29_ladder.json")
    if os.path.exists(lad):
        ld = json.load(open(lad))
        for key in ("ladder_sim", "ladder_real", "ladder_msprime"):
            if key in ld:
                s29[key] = ld[key]
    summary["s29_paired"] = s29_paired
    summary["s29_ladder"] = s29
    if s29_paired:
        md += ["## S29 — pooled paired negation sweep (all seeds, shards pooled)", "",
               "| cell | PC-AF [95% CI] | P(delta>0) | n seeds |",
               "|---|---|---|---|"]
        for k in sorted(s29_paired):
            v = s29_paired[k]
            md.append("| %s | %+.4f [%+.4f,%+.4f] | %.3f | %d |" % (
                k, v["delta_mean"], v["delta_ci_lo"], v["delta_ci_hi"],
                v["p_delta_gt0"], v["n_seeds"]))
        md.append("")
    for corp in ("ladder_sim", "ladder_msprime"):
        if s29.get(corp):
            md += [f"### S29 ladder — {corp}", "", "| k | PC AUROC |", "|---|---|"]
            for k in sorted(s29[corp], key=lambda x: (not x.isdigit(), int(x) if x.isdigit() else 0)):
                v = s29[corp][k]
                if isinstance(v, dict) and "mean" in v:
                    md.append("| %s | %.3f ± %.3f |" % (k, v["mean"], v["std"]))
                else:
                    md.append("| %s | %s |" % (k, v))
            md.append("")
    if s29.get("ladder_real"):
        md += ["### S29 ladder — ladder_real (per chromosome)", ""]
        lr = s29["ladder_real"]
        # real is nested: {chrom: {af_only, ladder:{k:val}, eig_only}}
        if "ladder" in lr:                       # flat single-chrom form
            lr = {"all": lr}
        for chrom, blk in lr.items():
            if not isinstance(blk, dict) or "ladder" not in blk:
                continue
            md += [f"**{chrom}** (AF-only {blk.get('af_only', float('nan')):.3f}, "
                   f"eig-only {blk.get('eig_only', float('nan')):.3f})",
                   "", "| k | PC AUROC |", "|---|---|"]
            for k in sorted(blk["ladder"], key=lambda x: int(x) if str(x).isdigit() else 0):
                md.append("| %s | %.3f |" % (k, blk["ladder"][k]))
            md.append("")

    # ---- s30 density
    s30 = load("s30_density.json")
    summary["s30_density"] = s30
    if s30:
        md += ["## S30 — real marker-density robustness", "",
               "| chr | tier | markers | AF | PC | PC-AF |", "|---|---|---|---|---|---|"]
        for c in sorted(s30):
            for tier, v in s30[c].items():
                if "error" in v:
                    md.append("| %s | %s | — | error | | |" % (c, tier))
                else:
                    md.append("| %s | %s | %d | %.3f | %.3f | %+.3f |" % (
                        c, tier, v["n_markers"], v["af"], v["pc"], v["delta"]))
        md.append("")

    # ---- s31 five-pop
    s31 = load("s31_fivepop.json")
    summary["s31_fivepop"] = s31
    if s31:
        md += ["## S31 — all five 1000G super-populations", "",
               "| panel | AF | PC | PC-AF | n_site |", "|---|---|---|---|---|"]
        for k, v in sorted(s31.items()):
            if k == "sups5" or not isinstance(v, dict):
                continue
            if "error" in v:
                md.append("| %s | error: %s | | | |" % (k, v["error"][:60]))
            else:
                md.append("| %s | %.3f | %.3f | %+.3f | %d |" % (
                    k, v["af"], v["pc"], v["delta"], v["n_site"]))
        md.append("")

    # ---- s32/s36 phased IBD
    for tag, fn in (("s32", "s32_phased_ibd.json"), ("s36", "s36_phased_ibd.json")):
        d = load(fn)
        summary[f"{tag}_phased_ibd"] = d
        if d:
            md += [f"## {tag.upper()} — real phased IBD (H0/H1 pairwise longest shared run)", ""]
            pc = d.get("positive_control", {})
            if pc and "agg" in pc:
                md.append("positive control: planted LSR = %.3f, unplanted = %.3f" % (
                    pc.get("agg", {}).get("planted", [float("nan")])[0],
                    pc.get("agg", {}).get("unplanted", [float("nan")])[0]))
            # s36 schema: {"agg": {"planted": {...}, "real": {...}}, "per_split": ...}
            if "agg" in d and isinstance(d["agg"], dict):
                a = d["agg"]
                if "planted" in a:
                    md.append("- planted control: AUROC %.3f ± %.3f" % (
                        a["planted"]["auc"][0], a["planted"]["auc"][1]))
                if "real" in a:
                    md.append("- real arm: AUROC %.3f ± %.3f (mem %.0f / non %.0f)" % (
                        a["real"]["auc"][0], a["real"]["auc"][1],
                        a["real"]["mem"][0], a["real"]["non"][0]))
            for key in ("real", "real_chr22"):
                if key in d and isinstance(d[key], dict) and "agg" in d[key]:
                    a = d[key]["agg"]
                    if "lsr_auc" in a:
                        md.append("- %s: LSR AUROC %.3f vs AF %.3f (mem %.0f / non %.0f)" % (
                            key, a["lsr_auc"][0], a["af"][0], a["mean_mem"][0], a["mean_non"][0]))
                elif key in d and isinstance(d[key], dict) and "per_L" in d[key]:
                    for L, v in d[key]["per_L"].items():
                        md.append("- %s %s: LSR AUROC %.3f (AF %.3f)" % (key, L, v["lsr_auc"][0], v["af"][0]))
            md.append("")

    # ---- s33 meta-attack
    s33 = load("s33_meta_attack.json")
    summary["s33_meta"] = s33
    if s33:
        md += ["## S33 — nonlinear meta-attack (structural-zero confirmation)", "",
               "| feature set | logistic | MLP |", "|---|---|---|"]
        for k in s33["logistic"]:
            md.append("| %s | %.3f | %.3f |" % (k, s33["logistic"][k]["mean"], s33["mlp"][k]["mean"]))
        md.append("")

    # ---- s34 parser bench
    s34 = load("s34_parse_bench.json")
    summary["s34_parse_bench"] = s34
    if s34:
        md += ["## S34 — VCF parser benchmark (anti-dressing control)", ""]
        for k, v in s34.items():
            md.append("- **%s**: %s" % (k, json.dumps(v)))

    # ---- s35 frontier
    s35 = load("s35_frontier.json")
    summary["s35_frontier"] = s35
    if s35:
        md += ["", "## S35 — AF-dominance frontier", "",
               "| cell | AF | PC | PC-AF | combined |", "|---|---|---|---|---|"]
        for k in sorted(s35["grid"]):
            v = s35["grid"][k]
            md.append("| %s | %.3f | %.3f | %+.3f | %.3f |" % (
                k, v["af"], v["pc"], v["delta"], v["combined"]))
        md.append("")

    with open(os.path.join(RAW, "gpu_round_summary.json"), "w") as f:
        json.dump(summary, f, indent=2)
    with open(OUT_MD, "w") as f:
        f.write("\n".join(md))
    print("wrote", OUT_MD)
    print("wrote", os.path.join(RAW, "gpu_round_summary.json"))


if __name__ == "__main__":
    main()
