"""S37 - biobank-scale semi-synthetic cohort with real haplotype structure.

Closes the "the real arm is capped at the 1000G sample set" limitation: the real
PC<AF attenuation could be a small-n artefact. Here cohorts are generated by
Li-Stephens mosaic copying from the real 1000G phased library
(`semi_synthetic.py`), so they carry REAL haplotype/LD structure, at sizes far
beyond 1000G (up to biobank nsp), and the SAME attack battery as `s27_gpu_scale`
is applied:

  per cell: af_only, train-half-calibrated PC, logistic-combined, paired
  PC-AF gap, reference-fitted-basis control, eigenvalue-only control, in-sample
  gap, fst_like.

Controls (per cohort): LD-decay match to the donor library, relatedness match,
AF spectrum, top-10 eigenvalue fraction — a cell is only trusted if its controls
pass (the LD/relatedness guard against shared-donor IBD inflation at large n).

Cohorts are cached to results/cache/semisyn_<chrom>_nsp<N>_m<M>_s<seed>.npz.
Usage:  python3 code/s37_realsynth_scale.py [shard] [nshards]
Output: results/raw/s37_realsynth_scale_shard<s>.json
"""
import json
import os
import sys
import time
import numpy as np
import torch

sys.path.insert(0, "/data/lvvyongji1/GWAS/code")
import common_gpu as cg
import semi_synthetic as ss

OUT = "/data/lvvyongji1/GWAS/results/raw"
CACHE = "/data/lvvyongji1/GWAS/results/cache"
DEV = torch.device("cuda")


def fst_like_np(G, anc):
    af = G.mean(0, dtype=np.float64) / 2.0
    hs = np.mean([2 * (G[anc == k].mean(0, dtype=np.float64) / 2.0)
                  * (1 - G[anc == k].mean(0, dtype=np.float64) / 2.0)
                  for k in np.unique(anc)], axis=0)
    ht = 2 * af * (1 - af)
    return float(np.nanmean((ht - hs) / np.where(ht > 0, ht, np.nan)))


def auroc_lr(tr_scores, tr_y, te_scores, te_y):
    """Out-of-fold logistic calibration/combination on the columns of
    `tr_scores` (shape (n, k)) fit on the train half, evaluated on the test
    half. With k=1 this is the train-half-calibrated single channel; with k=2 it
    is the AF+PC combination."""
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import roc_auc_score
    Xtr = np.asarray(tr_scores, float).reshape(len(tr_y), -1)
    Xte = np.asarray(te_scores, float).reshape(len(te_y), -1)
    lr = LogisticRegression(max_iter=1000).fit(Xtr, tr_y)
    return float(roc_auc_score(te_y, lr.predict_proba(Xte)[:, 1]))


def get_cohort(chrom, nsp, M, seed):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, f"semisyn_chr{chrom}_nsp{nsp}_m{M}_s{seed}.npz")
    if os.path.exists(path):
        z = np.load(path, allow_pickle=True)
        return dict(G=z["G"], ancestry=z["ancestry"], pos=z["pos"], M=int(z["M"]))
    c = ss.generate_cohort(chrom, n_per_group=nsp, rho=1e-7, seed=seed, stride_to=M)
    np.savez(path, G=c["G"], ancestry=c["ancestry"], pos=c["pos"], M=c["M"])
    return dict(G=c["G"], ancestry=c["ancestry"], pos=c["pos"], M=int(c["M"]))


def gram_topk_subset(G_host, subset, k=10, block=20000):
    """Exact top-k PCA fitted on a SUBSET of the study rows (the standard
    train-half-fitted basis). The study's own 3-way split gives 3*nsp rows; the
    Gram is n_train x n_train, so a cell at nsp=12000 (36000 study rows) is fitted
    on at most `subset` rows. Returns (eig (k,), loadings (k, M) GPU)."""
    G = G_host[subset]
    return cg.gram_svd_host(G, k=k, block=block)


def cell(nsp, M, seed, chrom=22, k=10, blk=50000, n_fit=20000):
    coh = get_cohort(chrom, nsp, M, seed)
    G, anc = coh["G"], coh["ancestry"]
    pop = dict(G=G, ancestry=anc, n_groups=3)
    site, ref, non = cg.split_population3_host(pop, nsp, nsp, nsp, seed=seed)
    n_s = site["G"].shape[0]
    rng0 = np.random.default_rng(seed + 77)
    fit_idx = np.sort(rng0.permutation(n_s)[:min(n_fit, n_s)])
    ev, L = gram_topk_subset(site["G"], fit_idx, k=k, block=blk)
    mu = site["G"].mean(0, dtype=np.float64)
    af_s = site["G"].mean(0, dtype=np.float64) / 2.0
    af_r = ref["G"].mean(0, dtype=np.float64) / 2.0

    am = cg.af_lrt_host(site["G"], af_s, af_r, block=blk)
    an = cg.af_lrt_host(non["G"], af_s, af_r, block=blk)
    dm = cg.proj_dist_host(site["G"], L, mu, block=blk)
    dn = cg.proj_dist_host(non["G"], L, mu, block=blk)
    n_n = non["G"].shape[0]

    rng = np.random.default_rng(seed + 313)
    tsm = torch.as_tensor(rng.random(n_s) < 0.5, device=DEV)
    tsn = torch.as_tensor(rng.random(n_n) < 0.5, device=DEV)
    ytr = torch.cat([torch.ones(int(tsm.sum()), device=DEV),
                     torch.zeros(int(tsn.sum()), device=DEV)])
    yte = torch.cat([torch.ones(int((~tsm).sum()), device=DEV),
                     torch.zeros(int((~tsn).sum()), device=DEV)])
    pc_tr = torch.cat([dm[tsm], dn[tsn]])
    sgn = 1.0 if cg.auroc_gpu(-pc_tr, ytr) >= cg.auroc_gpu(pc_tr, ytr) else -1.0
    pcm = sgn * (-dm); pcn = sgn * (-dn)
    af_tr = torch.cat([am[tsm], an[tsn]]); af_te = torch.cat([am[~tsm], an[~tsn]])
    pc_te = torch.cat([pcm[~tsm], pcn[~tsn]])
    af_auc = float(cg.auroc_gpu(af_te, yte))
    pc_auc = float(cg.auroc_gpu(pc_te, yte))
    ytr_np = ytr.cpu().numpy(); yte_np = yte.cpu().numpy()
    af_tr_np = af_tr.cpu().numpy(); af_te_np = af_te.cpu().numpy()
    pcm_np = pcm.cpu().numpy(); pcn_np = pcn.cpu().numpy()
    # combined = joint AF+PC logistic (both columns), calibrated out-of-sample
    comb = auroc_lr(np.column_stack([af_tr_np, np.concatenate([pcm_np[tsm.cpu().numpy()],
                                                              pcn_np[tsn.cpu().numpy()]])]),
                    ytr_np,
                    np.column_stack([af_te_np, np.concatenate([pcm_np[~tsm.cpu().numpy()],
                                                               pcn_np[~tsn.cpu().numpy()]])]),
                    yte_np)

    res = dict(af_only=af_auc, pc_calibrated=pc_auc, combined=comb,
               delta_pc_minus_af=pc_auc - af_auc,
               ev_top1_frac=float(ev[0] / (n_s * M)),
               ev_top10_frac=float(ev.sum() / (n_s * M)),
               fst_like=fst_like_np(site["G"], site["ancestry"]), n_site=n_s, M=M,
               n_fit=int(min(n_fit, n_s)), fit_frac=float(min(n_fit, n_s) / n_s))
    # reference-fitted basis control (in-sample mechanism control)
    rngb = np.random.default_rng(seed + 999)
    rf = ref["G"]; nrf = rf.shape[0]
    ridx = rngb.permutation(nrf)[:nrf // 2]
    mu_r = rf[ridx].mean(0, dtype=np.float64)
    _, L_r = cg.gram_svd_host(rf, indices=ridx, k=k, block=blk)
    rdm = cg.proj_dist_host(site["G"], L_r, mu_r, block=blk)
    rdn = cg.proj_dist_host(non["G"], L_r, mu_r, block=blk)
    pc_r_tr = torch.cat([rdm[tsm], rdn[tsn]])
    sgn_r = 1.0 if cg.auroc_gpu(-pc_r_tr, ytr) >= cg.auroc_gpu(pc_r_tr, ytr) else -1.0
    rc_te = torch.cat([sgn_r * (-rdm[~tsm]), sgn_r * (-rdn[~tsn])])
    res["pc_refbasis"] = float(cg.auroc_gpu(rc_te, yte))
    res["pc_in_sample_gap"] = pc_auc - res["pc_refbasis"]
    # eigenvalue-only control (random orthonormal basis, same k)
    rng_e = np.random.default_rng(seed + 4242)
    L_e = rng_e.normal(size=(k, M)).astype(np.float32)
    Q, _ = np.linalg.qr(L_e.T)
    L_e = torch.as_tensor(Q.T, device=DEV)
    edm = cg.proj_dist_host(site["G"], L_e, mu, block=blk)
    edn = cg.proj_dist_host(non["G"], L_e, mu, block=blk)
    pc_e_tr = torch.cat([edm[tsm], edn[tsn]])
    sgn_e = 1.0 if cg.auroc_gpu(-pc_e_tr, ytr) >= cg.auroc_gpu(pc_e_tr, ytr) else -1.0
    ec_te = torch.cat([sgn_e * (-edm[~tsm]), sgn_e * (-edn[~tsn])])
    res["pc_eigonly"] = float(cg.auroc_gpu(ec_te, yte))
    del L, L_r, L_e, site, ref, non, pop, coh, G
    torch.cuda.empty_cache()
    return res


def controls_cell(nsp, M, seed, chrom=22):
    """LD/relatedness/AF-spectrum/eig controls at one cell."""
    c = get_cohort(chrom, nsp, M, seed)
    d = ss.load_donors(chrom, stride_to=M)
    rep = ss.controls_report(dict(G=c["G"], ancestry=c["ancestry"], pos=c["pos"], M=c["M"]),
                             d, seed=seed)
    return rep


def grid_config():
    # (nsp, M) cells; large-nsp cells get a smaller marker set (cost), and one
    # large-n/high-M cell probes the biobank corner with real LD.
    cells = [(150, 8000), (500, 8000), (2000, 8000),
             (8000, 8000), (10000, 10000), (12000, 6000), (16000, 3000)]
    return dict(cells=cells, n_seeds=5, chrom=22)


def run(shard=0, nshards=1):
    cfg = grid_config()
    combos = cfg["cells"][shard::nshards]
    out_path = os.path.join(OUT, f"s37_realsynth_scale_shard{shard}.json")
    grid, controls = {}, {}
    t0 = time.time()
    for (nsp, M) in combos:
        rows = []
        for s in range(cfg["n_seeds"]):
            try:
                rows.append(cell(nsp, M, s, chrom=cfg["chrom"]))
            except RuntimeError as e:
                torch.cuda.empty_cache()
                if "out of memory" in str(e).lower():
                    print("OOM", nsp, M, flush=True)
                    break
                raise
            finally:
                import gc; gc.collect()
        if not rows:
            continue
        key = f"nsp{nsp}_m{M}"
        agg = {}
        for kk in rows[0]:
            agg[kk] = float(np.mean([r[kk] for r in rows]))
            if kk not in ("n_site", "M"):
                agg[kk + "_std"] = float(np.std([r[kk] for r in rows]))
        agg["n_seeds_used"] = len(rows)
        grid[key] = agg
        if key not in controls:
            controls[key] = controls_cell(nsp, M, 0, chrom=cfg["chrom"])
        print(key, json.dumps({kk: round(agg[kk], 4) for kk in
                               ("af_only", "pc_calibrated", "combined",
                                "delta_pc_minus_af", "pc_refbasis", "pc_eigonly",
                                "pc_in_sample_gap", "fst_like") if kk in agg}), flush=True)
        with open(out_path, "w") as f:
            json.dump(dict(grid=grid, controls=controls, cfg=cfg, shard=shard,
                           nshards=nshards, elapsed_s=round(time.time() - t0, 1)),
                      f, indent=2)
    print(f"shard{shard} done", round(time.time() - t0, 1), "s", flush=True)


if __name__ == "__main__":
    sh = int(sys.argv[1]) if len(sys.argv) > 1 else 0
    ns = int(sys.argv[2]) if len(sys.argv) > 2 else 1
    run(sh, ns)
